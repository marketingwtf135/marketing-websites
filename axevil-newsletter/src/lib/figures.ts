/**
 * Показатели платформы — один источник для всей страницы.
 *
 * Раньше эти цифры жили только в блоке «О платформе», и когда их понадобилось показать
 * ещё и в hero, это был бы второй набор значений, который неизбежно разъехался бы с
 * первым — ровно так уже случилось с числом подписчиков («1 000+ Клиентов» в одном блоке
 * против «1200+ wealth-менеджеров» в другом).
 *
 * Значения сверены с актуальной презентацией компании (2026-08-04): $200M+ AUM,
 * 35 компаний в портфеле, 150+ партнёров, 1000+ клиентов. Это третий набор цифр за два
 * дня, и стоит зафиксировать, какой источник чему соответствует:
 *
 *   показатель      сайт (было)   ТЗ         преза (сейчас)
 *   AUM             $150M         $150M      $200M+     ← оба прежних устарели
 *   компании        35            33         35         ← сайт был прав, ТЗ устарело
 *   партнёры        100+          150+       150+       ← ТЗ было право
 *   клиенты         1 000+        1 000+     1000+      ← совпадают
 *
 * Разряды разделены неразрывным пробелом, не запятой.
 *
 * Подписи: «Инвесторов» оставлено по ТЗ — с «Клиентов» из презы разница стилистическая, а
 * для этой аудитории «инвесторов» точнее. «WM-партнёров» заменено на «Партнёров», потому
 * что там разница смысловая, а не стилистическая (см. комментарий у значения).
 */
export interface Figure {
  /** Значение для крупной плашки: «$150M». */
  value: string
  /** Подпись под значением в блоке «О платформе»: «AUM». */
  label: string
  /** Слитная форма для строки-доказательства в hero: «$150M AUM». */
  inline: string
}

